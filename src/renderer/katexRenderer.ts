import katex, { type KatexOptions } from "katex";
import { parseMathSegments } from "../core/parser.js";
import type { MathDisplayMode, ValidationReason } from "../core/types.js";
import { validateLatex, type ValidationLimits } from "../core/validator.js";

/**
 * Output of the full text pipeline (`parseMathSegments -> validateLatex -> KaTeX`):
 * - `"text"`: plain text (inserted as a TextNode, never HTML -> XSS-safe).
 * - `"math"`: validated expression rendered by KaTeX to HTML + accessible MathML.
 * - `"rejected"`: rejected for safety or invalid LaTeX syntax; keeps `raw` for graceful fallback.
 */
export type RenderedSegment =
  | {
      type: "text";
      content: string;
    }
  | {
      type: "math";
      /** HTML + MathML generated by KaTeX with `trust: false`. */
      html: string;
      /** Original clean LaTeX source (useful for tooltips or click-to-copy). */
      latex: string;
      mode: MathDisplayMode;
      raw: string;
    }
  | {
      type: "rejected";
      reason: ValidationReason | "katex_error";
      message: string;
      raw: string;
    };

/**
 * Defensive KaTeX configuration (second layer of defense in depth):
 * - `output: "htmlAndMathml"`: crisp visual typesetting + native MathML for screen readers.
 * - `trust: false`: forbids raw HTML, links, and arbitrary styles inside KaTeX.
 * - `maxSize` / `maxExpand`: caps oversized rules and macro expansions (anti-DoS).
 * - `throwOnError: true`: caught cleanly so invalid syntax degrades back to original text.
 */
const KATEX_SAFE_BASE_OPTIONS: Readonly<KatexOptions> = {
  output: "htmlAndMathml",
  throwOnError: true,
  strict: "ignore",
  trust: false,
  maxSize: 10,
  maxExpand: 100,
};

/**
 * Validates a single expression with `validateLatex` and renders it to HTML + MathML string.
 */
export function renderFormula(
  latex: string,
  mode: MathDisplayMode,
  raw: string,
  limits?: Partial<ValidationLimits>
): RenderedSegment {
  const validation = validateLatex(latex, limits);
  if (!validation.ok) {
    return {
      type: "rejected",
      reason: validation.reason,
      message: validation.message,
      raw,
    };
  }

  try {
    const html = katex.renderToString(latex, {
      ...KATEX_SAFE_BASE_OPTIONS,
      displayMode: mode === "display",
    });

    return {
      type: "math",
      html,
      latex,
      mode,
      raw,
    };
  } catch (error) {
    const message =
      error instanceof Error
        ? error.message
        : "LaTeX syntax error while rendering with KaTeX.";

    return {
      type: "rejected",
      reason: "katex_error",
      message,
      raw,
    };
  }
}

export type DomRenderResult =
  | { ok: true }
  | {
      ok: false;
      reason: ValidationReason | "katex_error";
      message: string;
    };

/**
 * Validates an expression and renders it directly as DOM nodes inside `target`
 * via `katex.render()` (`createElement`/`appendChild`, zero `.innerHTML`).
 *
 * Essential on `x.com`, which enforces Trusted Types CSP (`require-trusted-types-for 'script'`)
 * and blocks direct `.innerHTML` assignments.
 */
export function renderFormulaToElement(
  latex: string,
  mode: MathDisplayMode,
  target: HTMLElement,
  limits?: Partial<ValidationLimits>
): DomRenderResult {
  const validation = validateLatex(latex, limits);
  if (!validation.ok) {
    return {
      ok: false,
      reason: validation.reason,
      message: validation.message,
    };
  }

  try {
    katex.render(latex, target, {
      ...KATEX_SAFE_BASE_OPTIONS,
      displayMode: mode === "display",
    });
    return { ok: true };
  } catch (error) {
    const message =
      error instanceof Error
        ? error.message
        : "LaTeX syntax error while rendering with KaTeX.";

    return {
      ok: false,
      reason: "katex_error",
      message,
    };
  }
}

/**
 * Full pure text pipeline: raw text -> parseMathSegments -> validateLatex -> KaTeX.
 */
export function renderTweetText(
  text: string,
  limits?: Partial<ValidationLimits>
): RenderedSegment[] {
  const segments = parseMathSegments(text);

  return segments.map((segment) => {
    if (segment.type === "text") {
      return segment;
    }

    return renderFormula(segment.content, segment.mode, segment.raw, limits);
  });
}
